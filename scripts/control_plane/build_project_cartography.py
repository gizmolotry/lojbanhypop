@dataclass
class FileEntry:
    path: str
    kind: str
    bucket: str
    status: str
    family: str
    lines: int
    bytes: int
    purpose: str
    has_main: bool = False
    functions: int = 0
    classes: int = 0
    imports: list[str] | None = None


def _run_git(args: list[str]) -> str:
    result = subprocess.run(["git", *args], cwd=REPO_ROOT, text=True, capture_output=True, check=False)
    if result.returncode != 0:
        return ""
    return result.stdout


def _tracked_files(paths: Iterable[str] | None = None) -> list[Path]:
    args = ["ls-files", "--cached", "--others", "--exclude-standard"]
    if paths:
        args.extend(paths)
    stdout = _run_git(args)
    seen: set[str] = set()
    out: list[Path] = []
    for line in stdout.splitlines():
        item = line.strip()
        if item and item not in seen:
            seen.add(item)
            out.append(REPO_ROOT / item)
    return out


def _rel(path: Path) -> str:
    return path.relative_to(REPO_ROOT).as_posix()


def _safe_read(path: Path) -> str:
    try:
        return path.read_text(encoding="utf-8")
    except UnicodeDecodeError:
        return path.read_text(encoding="utf-8", errors="replace")


def _line_count(text: str) -> int:
    return len(text.splitlines())


def _first_sentence(text: str, fallback: str = "") -> str:
    text = " ".join(str(text or "").strip().split())
    if not text:
        return fallback
    return text.split(". ")[0].strip(" .")[:160]


def _infer_family(rel: str) -> str:
    classified = classify_surface_path(rel)
    if classified.series != "unclassified":
        return classified.series
    parts = rel.split("/")
    joined = "/".join(parts[:3]).lower()
    for part in parts:
        low = part.lower()
        if re.fullmatch(r"m\d+", low):
            return low.upper()
        if low in {"m_bridge", "control_plane", "data", "training"}:
            return low
    match = re.search(r"(?:^|[_/\-])(m\d+)(?:[_/\-]|$)", joined)
    if match:
        return match.group(1).upper()
    if "j_series" in joined or "/j_" in joined:
        return "J"
    if "l_series" in joined or "/l_" in joined:
        return "L"
    if "h5" in joined:
        return "H5"
    return "shared"


def _bucket_status(path: Path) -> tuple[str, str, str]:
    rel = _rel(path)
    parts = rel.split("/")
    if parts[0] == "scripts":
        if path.suffix.lower() not in {".py", ".ps1"}:
            return "doc", "/".join(parts[:2]) if len(parts) > 1 else "scripts", "local-doc"
        bucket = "/".join(parts[:2]) if len(parts) > 1 else "scripts"
        if len(parts) > 1 and parts[1] == "legacy":
            status = "legacy-runnable"
        elif len(parts) > 1 and parts[1] == "control_plane":
            status = "active-control-plane"
        elif len(parts) > 1 and parts[1] in {"data", "training"}:
            status = "active-shared-utility"
        else:
            status = "active-family-runner"
        return "script", bucket, status
    if parts[:2] == ["airflow", "dags"]:
        if path.suffix.lower() != ".py":
            return "doc", "/".join(parts[:2]), "local-doc"
        bucket = "/".join(parts[:3]) if len(parts) > 2 else "airflow/dags"
        status = "legacy-dag" if "legacy" in parts else "active-dag"
        return "dag", bucket, status
    if parts[0] == "src":
        bucket = "/".join(parts[:3]) if len(parts) > 2 else "src"
        return "library", bucket, "active-library"
    if parts[0] == "tests":
        return "test", "tests", "active-test"
    if parts[0] == "docs":
        return "doc", "/".join(parts[:2]) if len(parts) > 1 else "docs", "human-doc"
    if parts[0] in {"configs", "config"}:
        return "config", parts[0], "configuration"
    return "other", parts[0], "tracked"


def _python_meta(path: Path, text: str) -> dict[str, Any]:
    meta: dict[str, Any] = {
        "purpose": "",
        "has_main": False,
        "functions": 0,
        "classes": 0,
        "imports": [],
    }
    try:
        tree = ast.parse(text)
    except SyntaxError:
        return meta
    doc = ast.get_docstring(tree)
    if doc:
        meta["purpose"] = _first_sentence(doc)
    imports: set[str] = set()
    for node in ast.walk(tree):
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            meta["functions"] += 1
        elif isinstance(node, ast.ClassDef):
            meta["classes"] += 1
        elif isinstance(node, ast.Import):
            for alias in node.names:
                imports.add(alias.name.split(".")[0])
        elif isinstance(node, ast.ImportFrom) and node.module:
            imports.add(node.module.split(".")[0])
        elif isinstance(node, ast.If):
            test = ast.dump(node.test)
            if "__main__" in test:
                meta["has_main"] = True
        elif isinstance(node, ast.Call):
            func_name = ""
            if isinstance(node.func, ast.Attribute):
                func_name = node.func.attr
            elif isinstance(node.func, ast.Name):
                func_name = node.func.id
            if func_name == "ArgumentParser":
                for kw in node.keywords:
                    if kw.arg == "description" and isinstance(kw.value, ast.Constant) and isinstance(kw.value.value, str):
                        meta["purpose"] = _first_sentence(kw.value.value, meta["purpose"])
    meta["imports"] = sorted(imports)[:12]
    return meta


def _purpose_from_name(path: Path) -> str:
    stem = path.stem.replace("_", " ").replace("-", " ")
    return stem[:1].upper() + stem[1:]


def build_entries() -> list[FileEntry]:
    paths = _tracked_files(["scripts", "airflow/dags", "src", "tests", "docs", "configs", "config"])
    entries: list[FileEntry] = []
    for path in paths:
        if not path.is_file():
            continue
        rel = _rel(path)
        if "__pycache__" in rel or rel.endswith(".pyc"):
            continue
        kind, bucket, status = _bucket_status(path)
        if kind not in {"script", "dag", "library", "test", "doc", "config"}:
            continue
        text = _safe_read(path)
        meta = _python_meta(path, text) if path.suffix == ".py" else {}
        purpose = str(meta.get("purpose") or "") if meta else ""
        if not purpose:
            purpose = _purpose_from_name(path)
        entries.append(
            FileEntry(
                path=rel,
                kind=kind,
                bucket=bucket,
                status=status,
                family=_infer_family(rel),
                lines=_line_count(text),
                bytes=path.stat().st_size,
                purpose=purpose,
                has_main=bool(meta.get("has_main", False)) if meta else path.suffix.lower() in {".ps1"},
                functions=int(meta.get("functions", 0)) if meta else 0,
                classes=int(meta.get("classes", 0)) if meta else 0,
                imports=list(meta.get("imports", [])) if meta else [],
            )
        )
    return sorted(entries, key=lambda item: item.path)


def _markdown_table(headers: list[str], rows: list[list[Any]]) -> str:
    out = ["| " + " | ".join(headers) + " |", "| " + " | ".join(["---"] * len(headers)) + " |"]
    for row in rows:
        cells = []
        for value in row:
            text = str(value).replace("\n", " ").replace("|", "\\|")
            cells.append(text)
        out.append("| " + " | ".join(cells) + " |")
    return "\n".join(out)


def _redundancy(entries: list[FileEntry]) -> dict[str, Any]:
    active_scripts = [e for e in entries if e.kind in {"script", "dag"}]
    by_bucket = defaultdict(list)
    for e in active_scripts:
        by_bucket[e.bucket].append(e)
    large = sorted([e for e in entries if e.lines >= 500], key=lambda e: e.lines, reverse=True)[:30]
    legacy = [e for e in active_scripts if "legacy" in e.status]
    family_runner_count = Counter(e.family for e in active_scripts if e.status == "active-family-runner")
    dag_family_count = Counter(e.family for e in active_scripts if e.kind == "dag")

    stem_groups: dict[str, list[FileEntry]] = defaultdict(list)
    for e in active_scripts:
        stem = Path(e.path).stem.lower()
        norm = re.sub(r"^(run|train|eval|build|render|summarize)_", "", stem)
        norm = re.sub(r"_dag$", "", norm)
        stem_groups[norm].append(e)
    similar_stems = {
        key: sorted([e.path for e in values])
        for key, values in stem_groups.items()
        if len(values) > 1
    }

    tracked_baselines = [e.path for e in entries if e.path.startswith("docs/baselines/test_m_series_baseline_")]
    archive_exports = [p for p in _tracked_files(["archive/exports"]) if p.is_file()]
    active_names = {Path(e.path).name for e in active_scripts}
    mirrored_exports = []
    for path in archive_exports:
        name = path.name
        if name.endswith(".txt"):
            possible = name[:-4]
            if possible in active_names:
                mirrored_exports.append(_rel(path))

    return {
        "large_files": [asdict(e) for e in large],
        "legacy_script_count": len(legacy),
        "legacy_script_lines": sum(e.lines for e in legacy),
        "family_runner_count": dict(sorted(family_runner_count.items())),
        "dag_family_count": dict(sorted(dag_family_count.items())),
        "similar_stem_clusters": similar_stems,
        "tracked_test_baselines": tracked_baselines,
        "mirrored_archive_exports_sample": mirrored_exports[:40],
        "mirrored_archive_exports_count": len(mirrored_exports),
        "bucket_counts": {bucket: len(values) for bucket, values in sorted(by_bucket.items())},
    }



