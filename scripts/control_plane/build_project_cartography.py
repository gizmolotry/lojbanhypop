def _write_manifest(entries: list[FileEntry], redundancy: dict[str, Any], generated_at: str) -> None:
    payload = {
        "generated_at": generated_at,
        "repo_root": str(REPO_ROOT),
        "series_order": series_order(),
        "known_series": sorted(known_series()),
        "summary": {
            "tracked_inventory_files": len(entries),
            "runnable_surfaces": sum(1 for e in entries if e.kind in {"script", "dag"}),
            "library_files": sum(1 for e in entries if e.kind == "library"),
            "test_files": sum(1 for e in entries if e.kind == "test"),
            "doc_files": sum(1 for e in entries if e.kind == "doc"),
            "config_files": sum(1 for e in entries if e.kind == "config"),
        },
        "series_counts": dict(sorted(Counter(e.family for e in entries).items())),
        "entries": [asdict(e) for e in entries],
        "redundancy": redundancy,
    }
    (DOCS_DIR / "project_cartography_manifest.json").write_text(json.dumps(payload, indent=2), encoding="utf-8")


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description="Build project cartography docs: script inventory, redundancy audit, and future scaffolding map.")
    parser.add_argument("--check", action="store_true", help="Build in memory and print summary without writing files.")
    args = parser.parse_args(argv)
    generated_at = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    entries = build_entries()
    redundancy = _redundancy(entries)
    if args.check:
        print(json.dumps({"entries": len(entries), "runnable": sum(1 for e in entries if e.kind in {"script", "dag"})}, indent=2))
        return
    DOCS_DIR.mkdir(parents=True, exist_ok=True)
    _write_root_index_stub(generated_at)
    _write_project_index(entries, redundancy, generated_at)
    _write_script_inventory(entries, generated_at)
    _write_redundancy(entries, redundancy, generated_at)
    _write_deprecation_ledger(entries, generated_at)
    _write_playbook(generated_at)
    _write_manifest(entries, redundancy, generated_at)
    print(f"Wrote project cartography docs under {DOCS_DIR}")
    print(f"Tracked inventory entries: {len(entries)}")
    print(f"Runnable surfaces: {sum(1 for e in entries if e.kind in {'script', 'dag'})}")


if __name__ == "__main__":
    main()
